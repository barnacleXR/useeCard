import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync,rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createApp } from '../src/app.js';
import { DatabaseService } from '../src/database.js';
import { randomUUID } from 'node:crypto';

test('密码轮换撤销其他会话、设备和配对码，审计筛选分页与所有权隔离',async()=>{
 const dir=mkdtempSync(join(tmpdir(),'ccm-security-'));
 process.env.DATABASE_PATH=join(dir,'data.db');process.env.COOKIE_SECURE='false';
 const app=await createApp();await app.listen(0,'127.0.0.1');const base=await app.getUrl();
 const request=(path:string,method='GET',body?:unknown,cookie='',csrf='')=>fetch(base+'/api'+path,{method,headers:{'Content-Type':'application/json',Cookie:cookie,'X-CSRF-Token':csrf,'User-Agent':'Security test browser'},body:body===undefined?undefined:JSON.stringify(body)});
 const password='a-good-password-123',next='another-good-password-456';
 try{
  const first=await request('/auth/setup','POST',{username:'owner',password});let cookie=first.headers.get('set-cookie')!.split(';')[0];let {csrf}=await first.json() as {csrf:string};
  const second=await request('/auth/login','POST',{username:'owner',password});const other=second.headers.get('set-cookie')!.split(';')[0];
  const sessions=await (await request('/auth/sessions','GET',undefined,cookie)).json() as any[];
  assert.equal(sessions.length,2);assert.equal(sessions.filter(v=>v.current).length,1);assert.ok(!JSON.stringify(sessions).includes('tokenHash'));assert.ok(!JSON.stringify(sessions).includes('csrf'));
  const current=sessions.find(v=>v.current),remote=sessions.find(v=>!v.current);
  assert.equal((await request(`/auth/sessions/${current.id}/revoke`,'POST',{},cookie,csrf)).status,400);
  assert.equal((await request(`/auth/sessions/${remote.id}/revoke`,'POST',{},cookie,'bad')).status,403);
  assert.equal((await request(`/auth/sessions/${remote.id}/revoke`,'POST',{},cookie,csrf)).status,201);
  const revoked=await request('/accounts','GET',undefined,other);assert.equal(revoked.status,401);assert.equal(revoked.headers.get('X-CCM-Session-Expired'),'1');
  await request('/auth/login','POST',{username:'owner',password});
  const device=await request('/app/v1/auth/login','POST',{username:'owner',password,deviceName:'Test phone',platform:'ios'});assert.equal(device.status,201);const tokens=await device.json() as any;
  await request('/devices/pairing-codes','POST',{},cookie,csrf);
  assert.equal((await request('/auth/password','POST',{currentPassword:password,newPassword:'short'},cookie,csrf)).status,400);
  assert.equal((await request('/auth/password','POST',{currentPassword:'wrong-password-123',newPassword:next},cookie,csrf)).status,401);
  assert.equal((await request('/auth/session','GET',undefined,cookie)).status,200);
  const changed=await request('/auth/password','POST',{currentPassword:password,newPassword:next},cookie,csrf);assert.equal(changed.status,201);
  const oldCookie=cookie,oldCsrf=csrf;cookie=changed.headers.get('set-cookie')!.split(';')[0];csrf=(await changed.json() as {csrf:string}).csrf;
  assert.notEqual(cookie,oldCookie);assert.notEqual(csrf,oldCsrf);
  assert.equal((await request('/auth/session','GET',undefined,oldCookie)).status,401);
  assert.equal((await request('/accounts','POST',{name:'test'},cookie,oldCsrf)).status,403);
  assert.equal((await request('/auth/login','POST',{username:'owner',password})).status,401);
  assert.equal((await request('/auth/session','GET',undefined,cookie)).status,200);
  assert.equal((await fetch(base+'/api/app/v1/accounts',{headers:{Authorization:'Bearer '+tokens.accessToken}})).status,401);
  assert.equal((await request('/app/v1/auth/refresh','POST',{refreshToken:tokens.refreshToken})).status,401);
  const db=app.get(DatabaseService).db;
  assert.equal((db.prepare('SELECT count(*) n FROM sessions').get() as any).n,1);
  assert.equal((db.prepare('SELECT count(*) n FROM device_sessions WHERE revokedAt IS NULL').get() as any).n,0);
  assert.equal((db.prepare('SELECT count(*) n FROM pairing_codes').get() as any).n,0);
  const owner=(db.prepare('SELECT id FROM users').get() as any).id;
  const insert=db.prepare('INSERT INTO audit_events(id,ownerId,action,entityId,changes,createdAt) VALUES(?,?,?,?,?,?)');
  insert.run(randomUUID(),owner,'test.boundary','test',JSON.stringify({nested:{password:'DO-NOT-LEAK',csrf:'HIDDEN',name:'visible'}}),'2026-10-20T15:00:00.000Z');
  insert.run(randomUUID(),owner,'test.boundary','before','{}','2026-10-20T14:59:59.999Z');
  insert.run(randomUUID(),'someone-else','test.boundary','other','{}','2026-10-20T15:00:00.000Z');
  const audit=await (await request('/audit?action=test.boundary&from=2026-10-21&to=2026-10-21&pageSize=1','GET',undefined,cookie)).json() as any;
  assert.equal(audit.total,1);assert.equal(audit.items[0].entityId,'test');assert.deepEqual(audit.items[0].changes,{nested:{name:'visible'}});
  const all=await (await request('/audit?pageSize=1','GET',undefined,cookie)).json() as any;
  const page2=await (await request('/audit?pageSize=1&page=2','GET',undefined,cookie)).json() as any;
  assert.ok(all.total>1);assert.notEqual(all.items[0].id,page2.items[0].id);
  assert.equal((await request('/audit?pageSize=101','GET',undefined,cookie)).status,400);
  assert.equal((await request('/audit?from=2026-02-30','GET',undefined,cookie)).status,400);
  assert.equal((await request('/audit?from=2026-10-22&to=2026-10-21','GET',undefined,cookie)).status,400);
  assert.ok(!JSON.stringify(db.prepare("SELECT changes FROM audit_events WHERE action LIKE 'auth.%'").all()).includes(password));
  const relogin=await request('/auth/login','POST',{username:'owner',password:next});assert.equal(relogin.status,201);
 }finally{app.get(DatabaseService).close();await app.close();rmSync(dir,{recursive:true,force:true});}
});
